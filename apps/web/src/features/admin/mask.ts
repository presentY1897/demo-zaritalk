/**
 * 어드민 조회 화면의 **개인정보 마스킹** (T6.3) — 규칙은 여기 한 곳뿐이다.
 *
 * ## 결정: 마스킹한다. 그리고 **서버(DTO)에서** 한다
 *
 * 조회 화면은 운영자가 "누구인지 식별" 하려고 보는 화면이지 "연락" 하는 화면이 아니다.
 * 목록 한 장에 수십 명의 전화번호가 원문으로 뜨는 상태는 어깨너머·화면공유·스크린샷으로
 * 그대로 새어 나간다. 그래서 **가운데 4자리를 가린다** — 뒷자리가 남아 식별에는 충분하고,
 * 번호 자체는 재사용할 수 없다.
 *
 * 가림은 **응답을 만들 때** 한다(T4.2 블라인드와 같은 원칙) — 원문이 브라우저 번들·개발자도구·
 * 네트워크 탭에 아예 내려가지 않는다. 어드민 화면이 실수로 원문을 그리는 일이 구조적으로 불가능하다.
 *
 * | 대상 | 처리 |
 * |---|---|
 * | 전화번호(회원·계약 세입자·발송 수신자) | `010-****-1111` |
 * | 이름 | **가리지 않는다** — 운영자가 사람을 특정하는 1차 키다 |
 * | 주소·건물명·호실 | 가리지 않는다 — 개인이 아니라 자산 식별자다 |
 * | 발송 본문 | **가리지 않는다** — 무엇을 보냈는지 확인하는 것이 그 화면의 목적이다 |
 * | 발송 본문 중 **OTP 인증번호** | **가린다** — 로그를 보는 것만으로 남의 계정에 로그인할 수 있다 |
 * | 트래킹 `anonId` | 앞 8자리만 — 가명 식별자라 비교만 되면 충분하다 |
 *
 * > **검색은 원문 기준으로 동작한다.** 마스킹은 표시 규칙이지 저장 규칙이 아니다
 * > (`01011111111` 로 검색하면 찾히고, 화면에는 가려진 채로 나온다).
 * >
 * > 기존 어드민 화면(환급 심사 T2.5·신고 처리 T4.2)은 신청자 전화번호를 원문으로 그린다.
 * > 그 화면의 응답은 이 task 소유가 아니라 손대지 않았다 — 같은 함수를 그 DTO 에 끼우면 끝난다.
 *
 * 순수 함수라 DB 없이 테스트한다.
 */
import { normalizePhone } from "@/lib/phone";

/** `01011111111` → `010-****-1111`. 형식이 다르면 앞 3자리만 남기고 나머지를 가린다. */
export function maskPhone(input: string | null | undefined): string {
  if (!input) return "";
  const digits = normalizePhone(input);
  if (digits.length === 11) return `${digits.slice(0, 3)}-****-${digits.slice(7)}`;
  if (digits.length === 10) return `${digits.slice(0, 3)}-***-${digits.slice(6)}`;
  if (digits.length <= 3) return "*".repeat(digits.length);
  return `${digits.slice(0, 3)}-${"*".repeat(digits.length - 3)}`;
}

/** 가명 식별자는 앞 8자리만 — 같은 브라우저인지 비교하는 데는 충분하다. */
export function maskAnonId(input: string | null | undefined): string {
  if (!input) return "";
  return input.length <= 8 ? input : `${input.slice(0, 8)}…`;
}

/**
 * OTP 발송 본문에서 인증번호를 지운다.
 *
 * 데모의 OTP 는 코드가 응답·발송로그에 그대로 노출된다(T0.3). 그건 **본인이 자기 코드를**
 * 보는 이야기고, 어드민 발송 이력에서 남의 코드가 읽히는 것은 계정 탈취 경로다.
 * 4자리 이상 연속 숫자를 전부 가린다 — 만료 시각 같은 다른 숫자가 함께 가려져도
 * 이 화면에서 잃을 정보가 아니다.
 */
export function maskOtpBody(body: string): string {
  return body.replace(/\d{4,}/g, "••••••");
}
